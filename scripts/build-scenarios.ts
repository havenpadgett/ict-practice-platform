// Builds the simulator's scenarios from their specs (scripts/scenarios/).
//   npm run scenarios                          build every spec, validate, write src/data/sim-scenarios/
//   npm run scenarios -- inspect <id> <tf> [<day> <HH:MM> <day> <HH:MM>]
//                                              print the candles of one timeframe, to author references against
//   npm run scenarios -- structure <id> <tf> [<day> <HH:MM> <day> <HH:MM>]
//                                              print swings and gaps on that timeframe
// A scenario that fails validation is never written. Everything built here is
// seeded data and says so (docs/ENGINE.md → Content).

import fs from "node:fs";
import path from "node:path";
import { buildScenario, clockToT, inspect as structure, tToClock, type Clock } from "./scenarios/lib";
import { SPECS } from "./scenarios/specs";
import { supportedModes } from "../src/lib/engine/modes";
import { validateScenario } from "../src/lib/engine/validate";
import type { Timeframe } from "../src/lib/engine/time";

const outDir = path.resolve(__dirname, "../src/data/sim-scenarios");
const [, , cmd, id, tf, d1, h1, d2, h2] = process.argv;

function window(): { from?: Clock; to?: Clock } {
  return d1 && h1 && d2 && h2 ? { from: [Number(d1), h1], to: [Number(d2), h2] } : {};
}

if (cmd === "inspect" || cmd === "structure") {
  const spec = SPECS.find((s) => s.id === id);
  if (!spec) throw new Error(`no spec ${id}. Known: ${SPECS.map((s) => s.id).join(", ")}`);
  const built = buildScenario({ ...spec, build: () => ({ title: "inspect" }) as never, ideal: undefined });
  const { from, to } = window();
  if (cmd === "structure") {
    for (const line of structure(built, tf as Timeframe, spec.calendar, from, to)) console.log(line);
  } else {
    const lo = from ? clockToT(spec.calendar, from) : -Infinity;
    const hi = to ? clockToT(spec.calendar, to) : Infinity;
    for (const c of built.ctx.series(tf as Timeframe)) if (c.t >= lo && c.t <= hi) console.log(tToClock(spec.calendar, c.t), c.o, c.h, c.l, c.c, c.c >= c.o ? "up" : "dn");
  }
} else {
  fs.mkdirSync(outDir, { recursive: true });
  let failed = 0;
  const catalog: Record<string, unknown>[] = [];
  for (const spec of SPECS) {
    const built = buildScenario(spec);
    const problems = validateScenario(built.scenario, { ideal: spec.ideal ? spec.ideal(built.ctx) : undefined });
    if (problems.length > 0) {
      failed += 1;
      console.error(`✗ ${spec.id}\n   ${problems.join("\n   ")}`);
      continue;
    }
    const s = built.scenario;
    fs.writeFileSync(path.join(outDir, `${s.id}.json`), JSON.stringify(s));
    catalog.push({
      id: s.id,
      title: s.title,
      difficulty: s.difficulty,
      type: s.type,
      instrument: s.instrument,
      seeded: s.provenance.kind === "seeded",
      skills: s.skills,
      tags: s.tags,
      modes: supportedModes(s),
      noTrade: s.reference.trade === null,
    });
    console.log(`✓ ${s.id}  ${s.title}  (${supportedModes(s).length} modes, ${s.data.stream.length} stream candles)`);
  }
  if (failed > 0) {
    console.error(`${failed} scenario(s) failed validation; nothing was registered.`);
    process.exit(1);
  }
  const ids = catalog.map((c) => c.id as string);
  const registry = `// Generated by scripts/build-scenarios.ts: do not edit.
// Scenario data is loaded lazily and only on the server (src/lib/engine/store.ts).

import type { Scenario } from "@/lib/engine/types";

type Loader = () => Promise<{ default: unknown }>;

export const SCENARIO_LOADERS: Record<string, Loader> = {
${ids.map((i) => `  ${JSON.stringify(i)}: () => import(${JSON.stringify(`./${i}.json`)}),`).join("\n")}
};

export type { Scenario };
`;
  fs.writeFileSync(path.join(outDir, "registry.ts"), registry);
  fs.writeFileSync(path.join(outDir, "catalog.json"), JSON.stringify(catalog, null, 1) + "\n");
  console.log(`Wrote ${ids.length} scenarios to ${path.relative(process.cwd(), outDir)}`);
}
