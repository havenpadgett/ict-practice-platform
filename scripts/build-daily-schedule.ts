// Extends src/data/daily-schedule.ts: one practice-ready Recognition
// exercise per UTC day, the same for everyone. Append-only on purpose:
// days already in the file are never changed (a shared daily link has to
// keep showing the chart it was shared with), so adding scenarios later
// only affects the days added after them.
//   npm run daily            extend to 365 days from the epoch
//   npm run daily -- 540     extend to 540 days
//
// The rules: the concept rotates through seven (so no concept is more than a
// week away), the difficulty through a cycle of five, and within a concept
// the least-used chart comes first (hand-built or human-reviewed before
// auto-approved), nearest the wanted difficulty. Charts repeat only once
// the concept's pool has been used; docs/OPERATIONS.md → Daily challenge.

import fs from "node:fs";
import path from "node:path";
import { exercises, isPracticeReady } from "../src/data/exercises";
import { DAILY_EPOCH, DAILY_SCHEDULE } from "../src/data/daily-schedule";
import { LANDING_EXERCISE_ID } from "../src/lib/challenge";

const CONCEPTS = ["FVG", "Liquidity", "MSS", "IFVG", "OrderBlock", "PremiumDiscount", "TimeLiquidity"] as const;
const DIFFICULTY_CYCLE = [1, 2, 2, 3, 2];

const pool = exercises
  // The front page's chart is not also a daily.
  .filter((e) => e.exercise_id !== LANDING_EXERCISE_ID)
  .filter((e) => isPracticeReady(e) && (e.answer_type === "zone" || e.answer_type === "level" || e.answer_type === "choice"))
  .map((e) => ({
    id: e.exercise_id,
    concept: e.concept as string,
    difficulty: e.difficulty,
    // Hand-built and human-reviewed charts before pipeline-approved ones.
    tier: !e.provenance || e.provenance.human_reviewed ? 0 : 1,
  }));

const target = Number(process.argv.slice(2).find((a) => /^\d+$/.test(a)) ?? 365);
const schedule = [...DAILY_SCHEDULE];
const used = new Map<string, number>();
for (const id of schedule) used.set(id, (used.get(id) ?? 0) + 1);

for (let day = schedule.length; day < target; day++) {
  const concept = CONCEPTS[day % CONCEPTS.length];
  const wanted = DIFFICULTY_CYCLE[day % DIFFICULTY_CYCLE.length];
  const candidates = pool
    .filter((p) => p.concept === concept)
    .sort(
      (a, b) =>
        (used.get(a.id) ?? 0) - (used.get(b.id) ?? 0) ||
        a.tier - b.tier ||
        Math.abs(a.difficulty - wanted) - Math.abs(b.difficulty - wanted) ||
        a.id.localeCompare(b.id),
    );
  const pick = candidates[0];
  if (!pick) throw new Error(`No practice-ready ${concept} exercise for day ${day}`);
  schedule.push(pick.id);
  used.set(pick.id, (used.get(pick.id) ?? 0) + 1);
}

const file = path.resolve(__dirname, "../src/data/daily-schedule.ts");
const body = `// One exercise id per UTC day, starting at DAILY_EPOCH: the daily challenge
// (src/lib/daily.ts). Generated by \`npm run daily\` and append-only: a day's
// chart never changes once it is in here, because people share the links.
// Only ids; the charts themselves are served the usual way, without keys.

export const DAILY_EPOCH = "${DAILY_EPOCH}";

export const DAILY_SCHEDULE: string[] = [
${schedule.map((id) => `  "${id}",`).join("\n")}
];
`;
fs.writeFileSync(file, body);
console.log(`Daily schedule: ${schedule.length} days from ${DAILY_EPOCH}, ${new Set(schedule).size} distinct charts`);
